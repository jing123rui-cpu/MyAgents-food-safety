"""Data schemas for the AI provider framework."""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional


@dataclass
class AIMessage:
    """A single message in a chat conversation."""
    role: str = "user"
    content: str = ""
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class AIRequest:
    """Request payload sent to an AI provider."""
    messages: List[AIMessage] = field(default_factory=list)
    system_prompt: str = ""
    temperature: float = 0.7
    max_tokens: int = 2048
    model: str = ""
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class AIResponse:
    """Response received from an AI provider."""
    content: str = ""
    model: str = ""
    usage: Dict[str, int] = field(default_factory=dict)
    finish_reason: str = ""
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class ImageAnalysis:
    """Result of analysing an image through an AI provider."""
    checkpoint_id: str = ""
    description: str = ""
    findings: List[str] = field(default_factory=list)
    risk_level: str = ""
    confidence: float = 0.0
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class DocumentAnalysis:
    """Result of analysing a document through an AI provider."""
    checkpoint_id: str = ""
    summary: str = ""
    key_points: List[str] = field(default_factory=list)
    compliance_issues: List[str] = field(default_factory=list)
    confidence: float = 0.0
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class ReportDraft:
    """A draft audit report generated by an AI provider."""
    title: str = ""
    summary: str = ""
    sections: Dict[str, str] = field(default_factory=dict)
    recommendations: List[str] = field(default_factory=list)
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class PromptTemplate:
    """A reusable prompt template with variable placeholders."""
    template: str = ""
    variables: List[str] = field(default_factory=list)
    description: str = ""
