    def _call_ai(self, prompt: str) -> str:
        """Send a prompt to the AI provider and return the response text."""
        request = AIRequest(
            messages=[AIMessage(role="user", content=prompt)],
            system_prompt=(
                "You are a professional food safety audit report writer for "
                "beverage manufacturing. Write in precise, regulatory-compliant "
                "language. Be specific and actionable."
            ),
            temperature=0.3,
            max_tokens=2048,
        )
        response: AIResponse = self._provider.chat(request)
        return response.content
