    @staticmethod
    def _offline_corrective_requirements(
        ctx: InspectionContext,
        ent: Optional[EnterpriseEvaluation],
    ) -> str:
        """Section 8 — 整改要求."""
        non_compliant = [r for r in ctx.evaluation_results if r.status == EvaluationStatus.NON_COMPLIANT]
        if not non_compliant and ent and ent.overall_result == "企业通过检查":
            return "本次监督检查未发现不符合项，企业应持续保持食品安全管理体系有效运行。"

        if not non_compliant:
            return "本次监督检查未发现不符合项，企业应持续保持食品安全管理体系有效运行。"

        lines = ["针对本次检查发现的不符合项，企业应采取以下整改措施：\n"]
        cp_map = {cp.checkpoint_id: cp for cp in ctx.matched_checkpoints}
        for i, er in enumerate(non_compliant, 1):
            cp = cp_map.get(er.checkpoint_id)
            cp_name = cp.checkpoint_name if cp else er.checkpoint_id
            lines.append(f"{i}. {cp_name}")
            if er.reason:
                lines.append(f"   问题：{er.reason}")
            if er.recommendation:
                lines.append(f"   措施：{er.recommendation}")
            else:
                lines.append("   措施：按照相关法规要求立即整改，完善管理制度和操作规程。")
            lines.append("")
        lines.append("整改期限由监督检查人员依法确定。")
        return "\n".join(lines).strip()

