    @staticmethod
    def _offline_risk_level(ctx: InspectionContext) -> str:
        """Determine risk level from inspection context."""
        if ctx.matched_risk_rules:
            levels = [r.risk_level for r in ctx.matched_risk_rules if r.risk_level]
            if "CRITICAL" in levels or "RISK-01" in levels:
                return "高风险"
            if "MAJOR" in levels or "RISK-02" in levels:
                return "中高风险"
            if "MODERATE" in levels or "RISK-03" in levels:
                return "中风险"
        if any(r.status == EvaluationStatus.NON_COMPLIANT for r in ctx.evaluation_results):
            return "中风险"
        return "低风险"

    @staticmethod
    def _offline_score(ctx: InspectionContext) -> float:
        """Calculate a deterministic score from evaluation results."""
        if not ctx.evaluation_results:
            return 0.0
        compliant = sum(1 for r in ctx.evaluation_results if r.status == EvaluationStatus.COMPLIANT)
        total = len(ctx.evaluation_results)
        return round(compliant / total, 2) if total else 0.0

