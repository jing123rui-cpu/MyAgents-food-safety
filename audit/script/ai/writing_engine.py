"""AuditWritingEngine — converts inspection findings into professional regulatory language.

Supports two modes:
- **Online**: calls PromptEngine → DeepSeekProvider → AI-generated text
- **Offline**: generates deterministic Chinese text from InspectionContext data (no AI required)
"""

